/**
 * 首启引导「性格」步的预设人设（2026-09-25 v2 引导）。
 *
 * 骨架 = 定位一句话 + 性格 + 说话习惯 + 底线 四段——与 OpenClaw 的 SOUL.md
 * （Persona / Voice / Boundaries）和用户提供的「糖糖」人设收敛一致；
 * 「小满」即糖糖骨架的通用化改写。全文作为 agent soul 写进系统人格。
 * 覆盖不同人群：女声向 / 男声向 / 中性。
 */
data class PersonaPreset(
    val key: String,
    val tag: String,
    /** 卡片上的一句话副注 */
    val tagline: String,
    /** 三段正文（性格 / 说话 / 底线） */
    val sections: List<String>
) {
    /** 写进 settings.soul 的全文。 */
    val fullText: String
        get() = "你是$key——$tagline\n\n" + sections.joinToString("\n\n")
}

