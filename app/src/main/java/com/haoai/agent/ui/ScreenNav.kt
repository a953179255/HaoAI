package com.haoai.agent.ui

/**
 * `screen` 编号的返回层级表。
 *
 * HaoAI 的换屏是 MainActivity 里一个 `screen: Int` 状态变量（不是 NavHost），
 * 所以**系统返回键不会自动"退一屏"**：每一屏得自己装一个 BackHandler  calling onBack，
 * 没装的那一屏就把返回键交给了系统 —— 结果是 Activity finish、应用被甩回桌面
 * （2026-09-30 真机实锤：电脑联动 19 就是这么一个洞，手势返回＝退出应用）。
 *
 * 这张表集中回答两个问题，好让新加一屏不再重复踩：
 *  - [depth]：转场动画该按 push 还是 pop 走（原来散在 `MainActivity.screenDepth`）；
 *  - [parentOf]：这一屏的上一级是谁，[null] 表示它就是根（聊天页）。
 *
 * MainActivity 用 [parentOf] 兜底装一层 BackHandler：页面自己有处理器时**后注册者优先**
 * （子组合比这行晚注册，所以弹窗、分区、抽屉那些仍旧归页面自己管），
 * 只有页面没接住时才按这张表退回上一级，而不是退出应用。
 * 页面里那个箭头按钮走的仍是各自的 `onBack`（有的还要顺带恢复侧边栏），这张表管不到它。
 */
object ScreenNav {

    /** 转场深度：数字大＝在更里层。聊天 0 是根。 */
    fun depth(s: Int): Int = when (s) {
        0 -> 0          // 聊天（根）
        1, 4, 7 -> 1    // 设置根 / 会话列表 / 浏览器
        2 -> 3          // 记忆库（记忆与梦境的下级）
        18 -> 3         // 搜索服务目录（搜索服务的下级）——过去记成 2，与它的上一级同层
        // 设置 section 子页 / 定时 / 技能 / MCP / 工作流 / 电脑联动 + 未知屏兜底
        // （2026-10-10 Nit：原先 in 9..17 与 else 都回 2，是冗余分支，合并；
        // parentOf 那边的 else -> 1 是**有意**兜底，不是冗余，保留）
        else -> 2
    }

    /** 这一屏的上一级；聊天页没有上一级（返回键该交给系统＝最小化）。 */
    fun parentOf(s: Int): Int? = when (s) {
        0 -> null
        1, 4, 7 -> 0            // 设置根 / 全部会话 / 浏览器 → 聊天
        2 -> 11                 // 记忆库 → 记忆与梦境（用户反馈过"返回该回上一级"）
        18 -> 17                // 搜索目录 → 搜索服务
        in 9..17 -> 1           // 各设置子页与 定时/技能/MCP/工作流/电脑联动 → 设置根
        else -> 1               // 兜底：未知屏回设置根，而不是退出应用
    }

    fun isRoot(s: Int): Boolean = parentOf(s) == null
}
